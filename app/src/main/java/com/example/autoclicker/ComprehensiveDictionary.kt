    /**
     * Attempts to find a translation for an English word using stemming.
     */
    fun lookupEnglish(word: String): String? {
        val lower = word.lowercase()
        // 1. Direct match
        EN_RU[lower]?.let { return it }

        // 2. Possessive 's
        if (lower.endsWith("'s") && lower.length > 2) {
            EN_RU[lower.substring(0, lower.length - 2)]?.let { return it }
        }

        // 3. Plural -s, -es
        if (lower.endsWith("ies") && lower.length > 3) {
            EN_RU[lower.substring(0, lower.length - 3) + "y"]?.let { return it }
        }
        if (lower.endsWith("es") && lower.length > 3) {
            EN_RU[lower.substring(0, lower.length - 2)]?.let { return it }
        }
        if (lower.endsWith("s") && lower.length > 2) {
            EN_RU[lower.substring(0, lower.length - 1)]?.let { return it }
        }

        // 4. Past tense -ed
        if (lower.endsWith("ed") && lower.length > 3) {
            EN_RU[lower.substring(0, lower.length - 2)]?.let { return it }
            EN_RU[lower.substring(0, lower.length - 1)]?.let { return it }
        }

        // 5. Participle -ing
        if (lower.endsWith("ing") && lower.length > 4) {
            EN_RU[lower.substring(0, lower.length - 3)]?.let { return it }
            EN_RU[lower.substring(0, lower.length - 3) + "e"]?.let { return it }
        }

        return null
    }

